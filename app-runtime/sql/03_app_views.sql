WITH fin AS (
  SELECT COMPANY_ID, REVENUE_JPY, OPERATING_PROFIT, NET_PROFIT, TOTAL_ASSETS, FISCAL_YEAR,
    ROUND(100.0*OPERATING_PROFIT/NULLIF(REVENUE_JPY,0),2) AS OP_MARGIN, EMPLOYEE_COUNT_YOY
  FROM (SELECT *, ROW_NUMBER() OVER (PARTITION BY COMPANY_ID ORDER BY FISCAL_YEAR DESC) RN
        FROM LIFEINSURANCE_DEMO_DB.RAW.T_FINANCIAL_DATA) WHERE RN=1
),
contracts AS (
  SELECT k.COMPANY_ID, COUNT(*) AS CONTRACT_COUNT, SUM(k.ANNUAL_PREMIUM) AS TOTAL_PREMIUM,
    SUM(k.INSURED_COUNT) AS TOTAL_INSURED, MIN(k.EXPIRY_DATE) AS NEAREST_EXPIRY,
    COUNT_IF(k.EXPIRY_DATE BETWEEN CURRENT_DATE() AND DATEADD(day,90,CURRENT_DATE())) AS EXPIRING_90D,
    ARRAY_AGG(DISTINCT p.PRODUCT_CATEGORY) AS COVERED_CATEGORY_LIST
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_CONTRACTS k
  LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_INSURANCE_PRODUCTS p ON p.PRODUCT_ID = k.PRODUCT_ID
  GROUP BY k.COMPANY_ID
),
jobs AS (
  SELECT COMPANY_ID, COUNT(*) AS POSTING_COUNT,
    COUNT_IF(POSTING_DATE >= DATEADD(day,-90,CURRENT_DATE())) AS RECENT_POSTINGS_90D,
    SUM(OPENINGS) AS TOTAL_OPENINGS, MAX(SIGNAL_STRENGTH) AS MAX_SIGNAL_STRENGTH,
    ARRAY_AGG(DISTINCT INSURANCE_SIGNAL_TYPE) AS SIGNAL_TYPES, MAX(POSTING_DATE) AS LATEST_POSTING_DATE
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_JOB_POSTINGS GROUP BY COMPANY_ID
),
touch AS (
  SELECT COMPANY_ID, COUNT(*) AS TOUCHPOINT_COUNT, MAX(TOUCHPOINT_DATE) AS LAST_TOUCH_DATE,
    DATEDIFF(day, MAX(TOUCHPOINT_DATE), CURRENT_DATE()) AS DAYS_SINCE_TOUCH,
    COUNT_IF(SENTIMENT='POSITIVE') AS POSITIVE_TOUCHES, COUNT(DISTINCT CONTACT_ID) AS CONTACTED_PEOPLE
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_CONTACT_TOUCHPOINTS GROUP BY COMPANY_ID
),
mtg AS (
  SELECT COMPANY_ID, COUNT(*) AS MEETING_COUNT, MAX(MEETING_DATE) AS LAST_MEETING_DATE,
    DATEDIFF(day, MAX(MEETING_DATE), CURRENT_DATE()) AS DAYS_SINCE_MEETING,
    ROUND(AVG(QUALITY_SCORE),1) AS AVG_MEETING_QUALITY,
    COUNT_IF(OUTCOME='成約') AS WON_MEETINGS, COUNT_IF(OUTCOME='停滞') AS STALLED_MEETINGS
  FROM LIFEINSURANCE_DEMO_DB.ANALYTICS.V_MEETING_QUALITY GROUP BY COMPANY_ID
),
pros AS (
  SELECT COMPANY_ID, COUNT(*) AS PROSPECT_COUNT, SUM(PROSPECT_AMOUNT) AS PIPELINE_AMOUNT,
    MAX(AI_SCORE) AS MAX_AI_SCORE, MIN(EXPECTED_CLOSE_DATE) AS NEAREST_CLOSE_DATE
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_PROSPECTS GROUP BY COMPANY_ID
),
news AS (
  SELECT COMPANY_ID, COUNT(*) AS NEWS_COUNT_90D, MAX(NEWS_DATE) AS LATEST_NEWS_DATE
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_COMPANY_NEWS
  WHERE NEWS_DATE >= DATEADD(day,-90,CURRENT_DATE()) GROUP BY COMPANY_ID
),
alerts AS (
  SELECT COMPANY_ID, COUNT(*) AS OPEN_ALERT_COUNT, MAX(DETECTED_AT) AS LATEST_ALERT_AT
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_EVENT_ALERTS
  WHERE COALESCE(STATUS,'OPEN') <> 'CLOSED' GROUP BY COMPANY_ID
),
acts AS (
  SELECT COMPANY_ID, COUNT_IF(STATUS='未着手') AS OPEN_ACTIONS,
    COUNT_IF(STATUS='遅延') AS OVERDUE_ACTIONS, MIN(IFF(STATUS='未着手', DUE_DATE, NULL)) AS NEXT_DUE_DATE
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_NEXT_ACTIONS GROUP BY COMPANY_ID
)
