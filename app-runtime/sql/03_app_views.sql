  c.TURNOVER_RATE, c.IS_LISTED, c.HAS_OVERSEAS_SUBSIDIARY, c.PENSION_TYPE, c.HEALTH_CERT_STATUS,
  c.PROSPECT_RANK, c.YEARS_IN_CHARGE, c.SALES_REP_ID,
  COALESCE(r.FULL_NAME,'未割当') AS SALES_REP_NAME, COALESCE(sk.SKILL_TIER,'未設定') AS REP_SKILL_TIER,
  f.FISCAL_YEAR AS LATEST_FISCAL_YEAR, f.REVENUE_JPY AS LATEST_REVENUE, f.OPERATING_PROFIT,
  f.NET_PROFIT, f.TOTAL_ASSETS, f.OP_MARGIN, f.EMPLOYEE_COUNT_YOY,
  COALESCE(k.CONTRACT_COUNT,0) AS CONTRACT_COUNT, COALESCE(k.TOTAL_PREMIUM,0) AS TOTAL_PREMIUM,
  COALESCE(k.TOTAL_INSURED,0) AS TOTAL_INSURED, k.NEAREST_EXPIRY, COALESCE(k.EXPIRING_90D,0) AS EXPIRING_90D,
  COALESCE(k.COVERED_CATEGORY_LIST, ARRAY_CONSTRUCT()) AS COVERED_CATEGORY_LIST,
  COALESCE(j.POSTING_COUNT,0) AS POSTING_COUNT, COALESCE(j.RECENT_POSTINGS_90D,0) AS RECENT_POSTINGS_90D,
  COALESCE(j.TOTAL_OPENINGS,0) AS TOTAL_OPENINGS, COALESCE(j.MAX_SIGNAL_STRENGTH,0) AS MAX_SIGNAL_STRENGTH,
  COALESCE(j.SIGNAL_TYPES, ARRAY_CONSTRUCT()) AS SIGNAL_TYPES, j.LATEST_POSTING_DATE,
  COALESCE(t.TOUCHPOINT_COUNT,0) AS TOUCHPOINT_COUNT, t.LAST_TOUCH_DATE,
  COALESCE(t.DAYS_SINCE_TOUCH,999) AS DAYS_SINCE_TOUCH, COALESCE(t.POSITIVE_TOUCHES,0) AS POSITIVE_TOUCHES,
  COALESCE(t.CONTACTED_PEOPLE,0) AS CONTACTED_PEOPLE,
  COALESCE(mt.MEETING_COUNT,0) AS MEETING_COUNT, mt.LAST_MEETING_DATE,
  COALESCE(mt.DAYS_SINCE_MEETING,999) AS DAYS_SINCE_MEETING, mt.AVG_MEETING_QUALITY,
  COALESCE(mt.WON_MEETINGS,0) AS WON_MEETINGS, COALESCE(mt.STALLED_MEETINGS,0) AS STALLED_MEETINGS,
  COALESCE(p.PROSPECT_COUNT,0) AS PROSPECT_COUNT, COALESCE(p.PIPELINE_AMOUNT,0) AS PIPELINE_AMOUNT,
  COALESCE(p.MAX_AI_SCORE,0) AS MAX_AI_SCORE, p.NEAREST_CLOSE_DATE,
  COALESCE(n.NEWS_COUNT_90D,0) AS NEWS_COUNT_90D, n.LATEST_NEWS_DATE,
  COALESCE(al.OPEN_ALERT_COUNT,0) AS OPEN_ALERT_COUNT, al.LATEST_ALERT_AT,
  COALESCE(ac.OPEN_ACTIONS,0) AS OPEN_ACTIONS, COALESCE(ac.OVERDUE_ACTIONS,0) AS OVERDUE_ACTIONS, ac.NEXT_DUE_DATE
FROM LIFEINSURANCE_DEMO_DB.RAW.T_CUSTOMER_COMPANIES c
LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_SALES_REPS r ON r.SALES_REP_ID = c.SALES_REP_ID
LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_SALES_REP_SKILLS sk ON sk.SALES_REP_ID = c.SALES_REP_ID
LEFT JOIN fin f ON f.COMPANY_ID = c.COMPANY_ID
LEFT JOIN contracts k ON k.COMPANY_ID = c.COMPANY_ID
LEFT JOIN jobs j ON j.COMPANY_ID = c.COMPANY_ID
LEFT JOIN touch t ON t.COMPANY_ID = c.COMPANY_ID
LEFT JOIN mtg mt ON mt.COMPANY_ID = c.COMPANY_ID
LEFT JOIN pros p ON p.COMPANY_ID = c.COMPANY_ID
LEFT JOIN news n ON n.COMPANY_ID = c.COMPANY_ID
LEFT JOIN alerts al ON al.COMPANY_ID = c.COMPANY_ID
LEFT JOIN acts ac ON ac.COMPANY_ID = c.COMPANY_ID;
