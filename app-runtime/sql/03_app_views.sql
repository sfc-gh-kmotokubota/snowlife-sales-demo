	DAYS_SINCE_TOUCH,
	TOUCH_COUNT,
	HAS_DM_CONTACT,
	CONTACT_COUNT,
	ALERT_COUNT,
	LATEST_ALERT_DATE,
	DAYS_SINCE_ALERT,
	PIPELINE_AMOUNT,
	MAX_AI_SCORE,
	OP_MARGIN,
	EMPLOYEE_COUNT_YOY,
	SCORE_HIRING_SIGNAL,
	SCORE_CONTRACT_GAP,
	SCORE_FINANCIAL,
	SCORE_EVENT_FRESH,
	SCORE_CONTACT_GAP,
	SCORE_SCALE,
	SCORE_RENEWAL,
	W_HIRING,
	W_GAP,
	W_FIN,
	W_EVENT,
	W_TOUCH,
	W_SCALE,
	W_RENEWAL,
	TOTAL_SCORE,
	TRIGGERS,
	PRIMARY_TRIGGER,
	ATTACK_GRADE
) as
SELECT
  s.*,
  ARRAY_COMPACT(ARRAY_CONSTRUCT(
    IFF(s.EXPIRING_90D > 0,                                          '満期接近',       NULL),
    IFF(s.HAS_DM_CONTACT = 0,                                        'キーマン未接触', NULL),
    IFF(s.DAYS_SINCE_TOUCH > 150,                                    '接点劣化',       NULL),
    IFF(s.SCORE_HIRING_SIGNAL >= 85,                                 '求人シグナル強', NULL),
    IFF(s.SCORE_EVENT_FRESH >= 80,                                   '事業イベント',   NULL),
    IFF(s.SCORE_CONTRACT_GAP >= 70,                                  '契約空白大',     NULL),
    IFF(s.TURNOVER_RATE >= 4.0,                                      '離職率高',       NULL),
    IFF(s.HEALTH_CERT_STATUS = 'なし' AND s.SCORE_HIRING_SIGNAL >= 60,'健康経営未着手', NULL),
    IFF(s.PENSION_TYPE = 'DB' AND s.TOP_SIGNAL_TYPE = '年金制度',     'DC移行検討',     NULL)
  )) AS TRIGGERS,
  CASE
    WHEN s.EXPIRING_90D > 0 AND s.SCORE_RENEWAL >= 90 THEN '満期接近'
    WHEN s.HAS_DM_CONTACT = 0                         THEN 'キーマン未接触'
    WHEN s.DAYS_SINCE_TOUCH > 150                     THEN '接点劣化'
    WHEN s.SCORE_HIRING_SIGNAL >= 85                  THEN '求人シグナル強'
    WHEN s.SCORE_EVENT_FRESH >= 85                    THEN '事業イベント'
    WHEN s.SCORE_CONTRACT_GAP >= 70                   THEN '契約空白大'
    ELSE '定期フォロー'
  END AS PRIMARY_TRIGGER,
  CASE
    WHEN s.TOTAL_SCORE >= 75 THEN 'S'
    WHEN s.TOTAL_SCORE >= 65 THEN 'A'
    WHEN s.TOTAL_SCORE >= 55 THEN 'B'
    ELSE 'C'
  END AS ATTACK_GRADE
FROM LIFEINSURANCE_DEMO_DB.ANALYTICS.V_ATTACK_LIST_SCORES s;

create or replace view LIFEINSURANCE_DEMO_DB.ANALYTICS.V_HIRING_SIGNAL(
	COMPANY_ID,
	COMPANY_NAME,
	INDUSTRY_LARGE,
	INSURANCE_SIGNAL_TYPE,
	POSTING_MONTH,
	POSTING_COUNT,
	TOTAL_OPENINGS,
	MAX_SIGNAL_STRENGTH,
	AVG_SIGNAL_STRENGTH,
	LATEST_POSTING_DATE,
	DAYS_SINCE_LATEST,
	SIGNAL_RATIONALE
) COMMENT='このテーブルには、企業の採用信号に関するデータが格納されています。各レコードは、企業の業界、保険信号の種類、採用状況、信号の強度など、企業の採用動向に関する情報を含みます。'
 as
SELECT
  j.COMPANY_ID,
  c.COMPANY_NAME,
  c.INDUSTRY_LARGE,
  j.INSURANCE_SIGNAL_TYPE,
  DATE_TRUNC('month', j.POSTING_DATE) AS POSTING_MONTH,
  COUNT(*) AS POSTING_COUNT,
  SUM(j.OPENINGS) AS TOTAL_OPENINGS,
  MAX(j.SIGNAL_STRENGTH) AS MAX_SIGNAL_STRENGTH,
  ROUND(AVG(j.SIGNAL_STRENGTH), 2) AS AVG_SIGNAL_STRENGTH,
  MAX(j.POSTING_DATE) AS LATEST_POSTING_DATE,
  DATEDIFF(day, MAX(j.POSTING_DATE), CURRENT_DATE()) AS DAYS_SINCE_LATEST,
  ANY_VALUE(j.SIGNAL_RATIONALE) AS SIGNAL_RATIONALE
FROM LIFEINSURANCE_DEMO_DB.RAW.T_JOB_POSTINGS j
JOIN LIFEINSURANCE_DEMO_DB.RAW.T_CUSTOMER_COMPANIES c ON c.COMPANY_ID = j.COMPANY_ID
GROUP BY 1,2,3,4,5;

