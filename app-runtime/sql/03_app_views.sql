	TOP_JOB_TITLE,
	COVERED_CATEGORY_COUNT,
	CONTRACT_COUNT,
	TOTAL_PREMIUM,
	NEAREST_EXPIRY,
	EXPIRING_90D,
	ALL_CATEGORIES,
