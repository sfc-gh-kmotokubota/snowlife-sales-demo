create or replace view LIFEINSURANCE_DEMO_DB.ANALYTICS.V_KEY_PERSON_COVERAGE(
	COMPANY_ID,
	COMPANY_NAME,
	SALES_REP_ID,
	SALES_REP_NAME,
	CONTACT_ID,
	CONTACT_NAME,
	TITLE,
	DEPARTMENT,
	CONTACT_ROLE,
	TOUCHPOINT_COUNT,
	LAST_TOUCHPOINT_DATE,
	DAYS_SINCE_TOUCH,
	POSITIVE_TOUCHES,
	FACE_TO_FACE_COUNT,
	COVERAGE_STATUS
) as
SELECT
  c.COMPANY_ID, c.COMPANY_NAME, c.SALES_REP_ID,
  COALESCE(r.FULL_NAME,'未割当') AS SALES_REP_NAME,
  ct.CONTACT_ID, ct.FULL_NAME AS CONTACT_NAME, ct.TITLE, ct.DEPARTMENT, ct.CONTACT_ROLE,
  COUNT(tp.TOUCHPOINT_ID) AS TOUCHPOINT_COUNT,
  MAX(tp.TOUCHPOINT_DATE) AS LAST_TOUCHPOINT_DATE,
  DATEDIFF(day, MAX(tp.TOUCHPOINT_DATE), CURRENT_DATE()) AS DAYS_SINCE_TOUCH,
  COUNT_IF(tp.SENTIMENT = 'POSITIVE') AS POSITIVE_TOUCHES,
  COUNT_IF(tp.TOUCHPOINT_TYPE IN ('訪問','会食')) AS FACE_TO_FACE_COUNT,
  CASE
    WHEN COUNT(tp.TOUCHPOINT_ID) = 0 THEN '未接触'
    WHEN DATEDIFF(day, MAX(tp.TOUCHPOINT_DATE), CURRENT_DATE()) > 180 THEN '接点劣化'
    WHEN COUNT(tp.TOUCHPOINT_ID) >= 5 THEN '良好'
    ELSE '接点浅い'
  END AS COVERAGE_STATUS
FROM LIFEINSURANCE_DEMO_DB.RAW.T_CUSTOMER_COMPANIES c
LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_SALES_REPS r ON r.SALES_REP_ID = c.SALES_REP_ID
LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_CONTACTS ct ON ct.COMPANY_ID = c.COMPANY_ID
LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_CONTACT_TOUCHPOINTS tp
  ON tp.CONTACT_ID = ct.CONTACT_ID AND tp.COMPANY_ID = ct.COMPANY_ID
GROUP BY 1,2,3,4,5,6,7,8,9;

create or replace view LIFEINSURANCE_DEMO_DB.ANALYTICS.V_MEETING_QUALITY(
	MEETING_ID,
	COMPANY_ID,
	COMPANY_NAME,
	INDUSTRY_LARGE,
	SALES_REP_ID,
	SALES_REP_NAME,
	SKILL_TIER,
	MEETING_DATE,
	MEETING_TYPE,
	AGENDA,
	DURATION_MINUTES,
	OUTCOME,
	NEXT_ACTION_AGREED,
	SUMMARY_ID,
	SUMMARY_TEXT,
	SENTIMENT,
	HEARING_QUESTION_COUNT,
	KEY_ISSUE_COUNT,
	NEED_COUNT,
	MISSED_COUNT,
	OBJECTION_COUNT,
	COMPLIANCE_ISSUE_COUNT,
	TURN_COUNT,
	DEEP_NEED_COUNT,
	OBJECTIONS_HANDLED,
	QUALITY_SCORE
) as
WITH need_depth AS (
  SELECT s.MEETING_ID,
    COUNT_IF(f.VALUE:depth::TEXT = '深層') AS DEEP_NEED_COUNT,
    COUNT_IF(f.VALUE:depth::TEXT IN ('深層','中層')) AS MID_DEEP_NEED_COUNT
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_MEETING_SUMMARIES s, LATERAL FLATTEN(input => s.CUSTOMER_NEEDS) f
  GROUP BY s.MEETING_ID
),
obj AS (
  SELECT s.MEETING_ID, COUNT_IF(f.VALUE:handled::BOOLEAN = TRUE) AS OBJECTIONS_HANDLED
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_MEETING_SUMMARIES s, LATERAL FLATTEN(input => s.OBJECTIONS) f
  GROUP BY s.MEETING_ID
),
turns AS (
  SELECT MEETING_ID, COUNT(*) AS TURN_COUNT FROM LIFEINSURANCE_DEMO_DB.RAW.T_MEETING_TRANSCRIPTS GROUP BY MEETING_ID
)
SELECT
  m.MEETING_ID, m.COMPANY_ID, c.COMPANY_NAME, c.INDUSTRY_LARGE,
  m.SALES_REP_ID, r.FULL_NAME AS SALES_REP_NAME, COALESCE(sk.SKILL_TIER,'未設定') AS SKILL_TIER,
  m.MEETING_DATE, m.MEETING_TYPE, m.AGENDA, m.DURATION_MINUTES,
  m.OUTCOME, m.NEXT_ACTION_AGREED,
  s.SUMMARY_ID, s.SUMMARY_TEXT, s.SENTIMENT,
  COALESCE(s.HEARING_QUESTION_COUNT, 0) AS HEARING_QUESTION_COUNT,
  COALESCE(ARRAY_SIZE(s.KEY_ISSUES),0) AS KEY_ISSUE_COUNT,
  COALESCE(ARRAY_SIZE(s.CUSTOMER_NEEDS),0) AS NEED_COUNT,
  COALESCE(ARRAY_SIZE(s.MISSED_OPPORTUNITIES),0) AS MISSED_COUNT,
  COALESCE(ARRAY_SIZE(s.OBJECTIONS),0) AS OBJECTION_COUNT,
  COALESCE(ARRAY_SIZE(s.COMPLIANCE_ISSUES),0) AS COMPLIANCE_ISSUE_COUNT,
  COALESCE(t.TURN_COUNT,0) AS TURN_COUNT,
  COALESCE(nd.DEEP_NEED_COUNT,0) AS DEEP_NEED_COUNT,
  COALESCE(o.OBJECTIONS_HANDLED,0) AS OBJECTIONS_HANDLED,
  COALESCE(LEAST(100, GREATEST(0, ROUND(
      LEAST(30, COALESCE(s.HEARING_QUESTION_COUNT,0) * 4.5)
    + LEAST(20, COALESCE(nd.MID_DEEP_NEED_COUNT,0) * 6.0)
    + IFF(COALESCE(m.NEXT_ACTION_AGREED,FALSE), 20, 0)
    + LEAST(15, COALESCE(o.OBJECTIONS_HANDLED,0) * 7.5)
    + CASE s.SENTIMENT WHEN 'POSITIVE' THEN 15 WHEN 'NEUTRAL' THEN 7 ELSE 0 END
    - LEAST(20, COALESCE(ARRAY_SIZE(s.MISSED_OPPORTUNITIES),0) * 4.0)
    - COALESCE(ARRAY_SIZE(s.COMPLIANCE_ISSUES),0) * 10
  ))), 0) AS QUALITY_SCORE
FROM LIFEINSURANCE_DEMO_DB.RAW.T_MEETINGS m
JOIN LIFEINSURANCE_DEMO_DB.RAW.T_CUSTOMER_COMPANIES c ON c.COMPANY_ID = m.COMPANY_ID
LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_SALES_REPS r ON r.SALES_REP_ID = m.SALES_REP_ID
LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_SALES_REP_SKILLS sk ON sk.SALES_REP_ID = m.SALES_REP_ID
LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_MEETING_SUMMARIES s ON s.MEETING_ID = m.MEETING_ID
LEFT JOIN need_depth nd ON nd.MEETING_ID = m.MEETING_ID
LEFT JOIN obj o ON o.MEETING_ID = m.MEETING_ID
LEFT JOIN turns t ON t.MEETING_ID = m.MEETING_ID;

create or replace view LIFEINSURANCE_DEMO_DB.ANALYTICS.V_ATTACK_LIST_SCORES(
	COMPANY_ID,
	COMPANY_NAME,
	INDUSTRY_LARGE,
	INDUSTRY_DETAIL,
	PREFECTURE,
	EMPLOYEE_COUNT,
	ANNUAL_REVENUE_JPY,
	PROSPECT_RANK,
	SALES_REP_ID,
	SALES_REP_NAME,
	PENSION_TYPE,
	HEALTH_CERT_STATUS,
	AVERAGE_AGE,
	TURNOVER_RATE,
	HAS_OVERSEAS_SUBSIDIARY,
	POSTING_COUNT,
	SIGNAL_TYPE_COUNT,
	RECENT_POSTINGS_90D,
	RECENT_OPENINGS_90D,
	MAX_SIGNAL_STRENGTH,
	STRONG_RECENT_POSTINGS,
	TOP_SIGNAL_TYPE,
	TOP_SIGNAL_RATIONALE,
	TOP_JOB_TITLE,
	COVERED_CATEGORY_COUNT,
	CONTRACT_COUNT,
	TOTAL_PREMIUM,
	NEAREST_EXPIRY,
	EXPIRING_90D,
	ALL_CATEGORIES,
	LAST_TOUCH_DATE,
	DAYS_SINCE_TOUCH,
	TOUCH_COUNT,
	HAS_DM_CONTACT,
	CONTACT_COUNT,
	ALERT_COUNT,
	LATEST_ALERT_DATE,
	DAYS_SINCE_ALERT,
	PIPELINE_AMOUNT,
	MAX_AI_SCORE,
	OP_MARGIN,
	EMPLOYEE_COUNT_YOY,
	SCORE_HIRING_SIGNAL,
	SCORE_CONTRACT_GAP,
	SCORE_FINANCIAL,
	SCORE_EVENT_FRESH,
	SCORE_CONTACT_GAP,
	SCORE_SCALE,
	SCORE_RENEWAL,
	W_HIRING,
	W_GAP,
	W_FIN,
	W_EVENT,
	W_TOUCH,
	W_SCALE,
	W_RENEWAL,
	TOTAL_SCORE
) as
WITH job_sig AS (
  SELECT COMPANY_ID,
    COUNT(*) AS POSTING_COUNT,
    COUNT(DISTINCT INSURANCE_SIGNAL_TYPE) AS SIGNAL_TYPE_COUNT,
    COUNT_IF(POSTING_DATE >= DATEADD(day,-90,CURRENT_DATE())) AS RECENT_POSTINGS_90D,
    SUM(IFF(POSTING_DATE >= DATEADD(day,-90,CURRENT_DATE()), OPENINGS, 0)) AS RECENT_OPENINGS_90D,
    MAX(SIGNAL_STRENGTH) AS MAX_SIGNAL_STRENGTH,
    COUNT_IF(POSTING_DATE >= DATEADD(day,-90,CURRENT_DATE()) AND SIGNAL_STRENGTH >= 4) AS STRONG_RECENT
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_JOB_POSTINGS GROUP BY COMPANY_ID
),
top_sig AS (
  SELECT COMPANY_ID, INSURANCE_SIGNAL_TYPE AS TOP_SIGNAL_TYPE, SIGNAL_RATIONALE AS TOP_SIGNAL_RATIONALE, TOP_JOB_TITLE
  FROM (
    SELECT COMPANY_ID, INSURANCE_SIGNAL_TYPE, SIGNAL_RATIONALE, JOB_TITLE AS TOP_JOB_TITLE,
      ROW_NUMBER() OVER (PARTITION BY COMPANY_ID ORDER BY SIGNAL_STRENGTH DESC, POSTING_DATE DESC, POSTING_ID) AS RN
    FROM LIFEINSURANCE_DEMO_DB.RAW.T_JOB_POSTINGS
  ) WHERE RN = 1
),
contract_cov AS (
  SELECT c.COMPANY_ID,
    COUNT(DISTINCT p.PRODUCT_CATEGORY) AS COVERED_CATEGORY_COUNT,
    COUNT(k.CONTRACT_ID) AS CONTRACT_COUNT,
    COALESCE(SUM(k.ANNUAL_PREMIUM), 0) AS TOTAL_PREMIUM,
    MIN(k.EXPIRY_DATE) AS NEAREST_EXPIRY,
    COUNT_IF(k.EXPIRY_DATE BETWEEN CURRENT_DATE() AND DATEADD(day,90,CURRENT_DATE())) AS EXPIRING_90D
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_CUSTOMER_COMPANIES c
  LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_CONTRACTS k ON k.COMPANY_ID = c.COMPANY_ID
  LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_INSURANCE_PRODUCTS p ON p.PRODUCT_ID = k.PRODUCT_ID
  GROUP BY c.COMPANY_ID
),
total_cats AS (SELECT GREATEST(COUNT(DISTINCT PRODUCT_CATEGORY),1) AS ALL_CATEGORIES FROM LIFEINSURANCE_DEMO_DB.RAW.T_INSURANCE_PRODUCTS),
touch AS (
  SELECT COMPANY_ID, MAX(TOUCHPOINT_DATE) AS LAST_TOUCH_DATE,
    DATEDIFF(day, MAX(TOUCHPOINT_DATE), CURRENT_DATE()) AS DAYS_SINCE_TOUCH, COUNT(*) AS TOUCH_COUNT
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_CONTACT_TOUCHPOINTS GROUP BY COMPANY_ID
),
keyperson AS (
  SELECT COMPANY_ID,
    MAX(IFF(CONTACT_ROLE='DECISION_MAKER' AND TOUCHPOINT_COUNT > 0, 1, 0)) AS HAS_DM_CONTACT,
    COUNT(DISTINCT CONTACT_ID) AS CONTACT_COUNT
  FROM LIFEINSURANCE_DEMO_DB.ANALYTICS.V_KEY_PERSON_COVERAGE GROUP BY COMPANY_ID
),
events AS (
  SELECT COMPANY_ID, COUNT(*) AS ALERT_COUNT, MAX(DETECTED_AT)::DATE AS LATEST_ALERT_DATE,
    DATEDIFF(day, MAX(DETECTED_AT)::DATE, CURRENT_DATE()) AS DAYS_SINCE_ALERT
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_EVENT_ALERTS
  WHERE COALESCE(STATUS,'OPEN') <> 'CLOSED' GROUP BY COMPANY_ID
),
prospect AS (
  SELECT COMPANY_ID, SUM(PROSPECT_AMOUNT) AS PIPELINE_AMOUNT, MAX(AI_SCORE) AS MAX_AI_SCORE, COUNT(*) AS PROSPECT_COUNT
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_PROSPECTS GROUP BY COMPANY_ID
),
fin AS (
  SELECT COMPANY_ID, REVENUE_JPY, OPERATING_PROFIT,
    ROUND(100.0 * OPERATING_PROFIT / NULLIF(REVENUE_JPY,0), 2) AS OP_MARGIN, EMPLOYEE_COUNT_YOY
  FROM (SELECT *, ROW_NUMBER() OVER (PARTITION BY COMPANY_ID ORDER BY FISCAL_YEAR DESC) AS RN
        FROM LIFEINSURANCE_DEMO_DB.RAW.T_FINANCIAL_DATA) WHERE RN = 1
),
scored AS (
  SELECT
    c.COMPANY_ID, c.COMPANY_NAME, c.INDUSTRY_LARGE, c.INDUSTRY_DETAIL, c.PREFECTURE,
    c.EMPLOYEE_COUNT, c.ANNUAL_REVENUE_JPY, c.PROSPECT_RANK, c.SALES_REP_ID,
    r.FULL_NAME AS SALES_REP_NAME, c.PENSION_TYPE, c.HEALTH_CERT_STATUS,
    c.AVERAGE_AGE, c.TURNOVER_RATE, c.HAS_OVERSEAS_SUBSIDIARY,
    COALESCE(js.POSTING_COUNT,0) AS POSTING_COUNT,
    COALESCE(js.SIGNAL_TYPE_COUNT,0) AS SIGNAL_TYPE_COUNT,
    COALESCE(js.RECENT_POSTINGS_90D,0) AS RECENT_POSTINGS_90D,
    COALESCE(js.RECENT_OPENINGS_90D,0) AS RECENT_OPENINGS_90D,
    COALESCE(js.MAX_SIGNAL_STRENGTH,0) AS MAX_SIGNAL_STRENGTH,
    COALESCE(js.STRONG_RECENT,0) AS STRONG_RECENT_POSTINGS,
    ts.TOP_SIGNAL_TYPE, ts.TOP_SIGNAL_RATIONALE, ts.TOP_JOB_TITLE,
    COALESCE(cc.COVERED_CATEGORY_COUNT,0) AS COVERED_CATEGORY_COUNT,
    COALESCE(cc.CONTRACT_COUNT,0) AS CONTRACT_COUNT, COALESCE(cc.TOTAL_PREMIUM,0) AS TOTAL_PREMIUM,
    cc.NEAREST_EXPIRY, COALESCE(cc.EXPIRING_90D,0) AS EXPIRING_90D, tc.ALL_CATEGORIES,
    t.LAST_TOUCH_DATE, COALESCE(t.DAYS_SINCE_TOUCH, 999) AS DAYS_SINCE_TOUCH, COALESCE(t.TOUCH_COUNT,0) AS TOUCH_COUNT,
    COALESCE(kp.HAS_DM_CONTACT,0) AS HAS_DM_CONTACT, COALESCE(kp.CONTACT_COUNT,0) AS CONTACT_COUNT,
    COALESCE(e.ALERT_COUNT,0) AS ALERT_COUNT, e.LATEST_ALERT_DATE, COALESCE(e.DAYS_SINCE_ALERT,999) AS DAYS_SINCE_ALERT,
    COALESCE(pr.PIPELINE_AMOUNT,0) AS PIPELINE_AMOUNT, COALESCE(pr.MAX_AI_SCORE,0) AS MAX_AI_SCORE,
    f.OP_MARGIN, f.EMPLOYEE_COUNT_YOY,
    COALESCE(LEAST(100, GREATEST(0, ROUND(
        COALESCE(js.SIGNAL_TYPE_COUNT,0) * 4.5
      + COALESCE(js.STRONG_RECENT,0) * 7.0
      + COALESCE(js.RECENT_POSTINGS_90D,0) * 1.2
      + LEAST(12, COALESCE(js.RECENT_OPENINGS_90D,0) / 30.0)
    ))), 0) AS SCORE_HIRING_SIGNAL,
    COALESCE(ROUND(100.0 * (tc.ALL_CATEGORIES - COALESCE(cc.COVERED_CATEGORY_COUNT,0)) / tc.ALL_CATEGORIES), 0) AS SCORE_CONTRACT_GAP,
    COALESCE(LEAST(100, GREATEST(0, ROUND(45 + COALESCE(f.OP_MARGIN,5) * 3.2 + COALESCE(f.EMPLOYEE_COUNT_YOY,0) * 2))), 45) AS SCORE_FINANCIAL,
    COALESCE(LEAST(100, GREATEST(0, ROUND(100 - COALESCE(e.DAYS_SINCE_ALERT,999) * 2.2))), 0) AS SCORE_EVENT_FRESH,
    COALESCE(LEAST(100, GREATEST(0, ROUND(COALESCE(t.DAYS_SINCE_TOUCH,999) / 3.5 + IFF(COALESCE(kp.HAS_DM_CONTACT,0)=0, 40, 0)))), 100) AS SCORE_CONTACT_GAP,
    COALESCE(LEAST(100, GREATEST(0, ROUND(LOG(10, GREATEST(COALESCE(c.EMPLOYEE_COUNT,1),1)) * 18))), 0) AS SCORE_SCALE,
    COALESCE(LEAST(100, GREATEST(0, ROUND(100 - DATEDIFF(day, CURRENT_DATE(), COALESCE(cc.NEAREST_EXPIRY, DATEADD(year,3,CURRENT_DATE()))) / 2.2))), 0) AS SCORE_RENEWAL
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_CUSTOMER_COMPANIES c
  LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_SALES_REPS r ON r.SALES_REP_ID = c.SALES_REP_ID
  CROSS JOIN total_cats tc
  LEFT JOIN job_sig js ON js.COMPANY_ID = c.COMPANY_ID
  LEFT JOIN top_sig ts ON ts.COMPANY_ID = c.COMPANY_ID
  LEFT JOIN contract_cov cc ON cc.COMPANY_ID = c.COMPANY_ID
  LEFT JOIN touch t ON t.COMPANY_ID = c.COMPANY_ID
  LEFT JOIN keyperson kp ON kp.COMPANY_ID = c.COMPANY_ID
  LEFT JOIN events e ON e.COMPANY_ID = c.COMPANY_ID
  LEFT JOIN prospect pr ON pr.COMPANY_ID = c.COMPANY_ID
  LEFT JOIN fin f ON f.COMPANY_ID = c.COMPANY_ID
)
SELECT s.*,
  ROUND(s.SCORE_HIRING_SIGNAL * 0.28, 2) AS W_HIRING,
  ROUND(s.SCORE_CONTRACT_GAP  * 0.18, 2) AS W_GAP,
  ROUND(s.SCORE_FINANCIAL     * 0.08, 2) AS W_FIN,
  ROUND(s.SCORE_EVENT_FRESH   * 0.14, 2) AS W_EVENT,
  ROUND(s.SCORE_CONTACT_GAP   * 0.12, 2) AS W_TOUCH,
  ROUND(s.SCORE_SCALE         * 0.06, 2) AS W_SCALE,
  ROUND(s.SCORE_RENEWAL       * 0.14, 2) AS W_RENEWAL,
  ROUND(  s.SCORE_HIRING_SIGNAL * 0.28 + s.SCORE_CONTRACT_GAP * 0.18
        + s.SCORE_FINANCIAL * 0.08     + s.SCORE_EVENT_FRESH * 0.14
        + s.SCORE_CONTACT_GAP * 0.12   + s.SCORE_SCALE * 0.06
        + s.SCORE_RENEWAL * 0.14, 1) AS TOTAL_SCORE
FROM scored s;

create or replace view LIFEINSURANCE_DEMO_DB.ANALYTICS.V_ATTACK_LIST(
