USE ROLE ACCOUNTADMIN;
USE WAREHOUSE LIFEINSURANCE_DEMO_WH;
USE DATABASE LIFEINSURANCE_DEMO_DB;

-- 01 で RAW テーブルを CREATE OR REPLACE すると、setup.sql で作った Search Service の
-- 変更追跡が切れるため、setup.sql 由来の2サービスもここで作り直す。
USE SCHEMA SEARCH;

create or replace cortex search service LIFEINSURANCE_DEMO_DB.SEARCH.JOB_POSTING_SEARCH
	ON SEARCH_TEXT
	attributes COMPANY_ID,JOB_CATEGORY,POSTING_DATE,INSURANCE_SIGNAL_TYPE
	warehouse='LIFEINSURANCE_DEMO_WH'
	target_lag='1 hour'
	refresh_mode=INCREMENTAL
	as (
  SELECT
    j.JOB_TITLE || ' ' || COALESCE(j.DEPARTMENT,'') || ' ' || COALESCE(j.JOB_DESCRIPTION,'') AS SEARCH_TEXT,
    j.POSTING_ID, j.COMPANY_ID, c.COMPANY_NAME, j.JOB_TITLE, j.DEPARTMENT, j.JOB_CATEGORY,
    j.POSTING_DATE::VARCHAR AS POSTING_DATE, j.OPENINGS, j.INSURANCE_SIGNAL_TYPE,
    j.SIGNAL_STRENGTH, j.SIGNAL_RATIONALE, j.SOURCE_SITE, j.WORK_LOCATION
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_JOB_POSTINGS j
  JOIN LIFEINSURANCE_DEMO_DB.RAW.T_CUSTOMER_COMPANIES c ON c.COMPANY_ID = j.COMPANY_ID
);

create or replace cortex search service LIFEINSURANCE_DEMO_DB.SEARCH.TACIT_KNOWLEDGE_SEARCH
	ON SEARCH_TEXT
	attributes KNOWLEDGE_ID,CATEGORY,APPLICABLE_INDUSTRY,SOURCE_REP_NAME
	warehouse='LIFEINSURANCE_DEMO_WH'
	target_lag='1 hour'
	refresh_mode=INCREMENTAL
	as (
  SELECT
    PATTERN_TITLE || ' ' || PATTERN_DETAIL || ' ' || COALESCE(WHEN_TO_USE,'') || ' ' || COALESCE(TALK_SCRIPT,'') AS SEARCH_TEXT,
    KNOWLEDGE_ID, CATEGORY, PATTERN_TITLE, PATTERN_DETAIL, WHEN_TO_USE, TALK_SCRIPT,
    APPLICABLE_INDUSTRY, SOURCE_REP_NAME, CONFIDENCE, WIN_RATE
  FROM LIFEINSURANCE_DEMO_DB.AI.T_TACIT_KNOWLEDGE
);

create or replace cortex search service LIFEINSURANCE_DEMO_DB.SEARCH.CUSTOMER_INFO_SEARCH
	ON TRANSCRIPT_TEXT
	attributes SPEAKER_LABEL,COMPANY_ID,MEETING_DATE,MEETING_TYPE,OUTCOME,SALES_REP_NAME
	warehouse='LIFEINSURANCE_DEMO_WH'
	target_lag='1 hour'
	refresh_mode=INCREMENTAL
	as (
  SELECT
    mt.TRANSCRIPT_TEXT, mt.SPEAKER_LABEL, mt.MEETING_ID,
    m.COMPANY_ID, m.MEETING_DATE::VARCHAR AS MEETING_DATE, m.MEETING_TYPE,
    m.AGENDA, m.OUTCOME, c.COMPANY_NAME, r.FULL_NAME AS SALES_REP_NAME
  FROM LIFEINSURANCE_DEMO_DB.RAW.T_MEETING_TRANSCRIPTS mt
  JOIN LIFEINSURANCE_DEMO_DB.RAW.T_MEETINGS m ON mt.MEETING_ID = m.MEETING_ID
  JOIN LIFEINSURANCE_DEMO_DB.RAW.T_CUSTOMER_COMPANIES c ON m.COMPANY_ID = c.COMPANY_ID
  LEFT JOIN LIFEINSURANCE_DEMO_DB.RAW.T_SALES_REPS r ON r.SALES_REP_ID = m.SALES_REP_ID
);

CREATE OR REPLACE CORTEX SEARCH SERVICE NEWS_SEARCH
  ON SEARCH_TEXT
  ATTRIBUTES COMPANY_ID, NEWS_DATE, EVENT_TYPE, INSURANCE_RELEVANCE
  WAREHOUSE = LIFEINSURANCE_DEMO_WH
  TARGET_LAG = '1 hour'
AS (
    SELECT
        n.HEADLINE || ' ' || COALESCE(n.BODY_TEXT, '') AS SEARCH_TEXT,
        n.HEADLINE,
        n.BODY_TEXT,
        n.COMPANY_ID,
        n.NEWS_DATE::VARCHAR AS NEWS_DATE,
        n.EVENT_TYPE,
        n.INSURANCE_RELEVANCE,
        n.NEWS_SOURCE,
        c.COMPANY_NAME
    FROM RAW.T_COMPANY_NEWS n
    JOIN RAW.T_CUSTOMER_COMPANIES c ON n.COMPANY_ID = c.COMPANY_ID
);

CREATE OR REPLACE CORTEX SEARCH SERVICE PRODUCT_SEARCH
  ON SEARCH_TEXT
  ATTRIBUTES PRODUCT_ID, PRODUCT_CATEGORY, PRODUCT_TYPE
  WAREHOUSE = LIFEINSURANCE_DEMO_WH
  TARGET_LAG = '24 hours'
AS (
    -- 保険商品
    SELECT
        ip.PRODUCT_NAME || ' ' || COALESCE(ip.DESCRIPTION, '') AS SEARCH_TEXT,
        ip.PRODUCT_ID,
        ip.PRODUCT_NAME,
        ip.DESCRIPTION,
        ip.PRODUCT_CATEGORY,
        ip.PRODUCT_TYPE,
        ip.TARGET_AUDIENCE,
        '保険商品' AS CONTENT_TYPE
    FROM RAW.T_INSURANCE_PRODUCTS ip

    UNION ALL

    -- 非保険サービス
    SELECT
        ns.SERVICE_NAME || ' ' || COALESCE(ns.DESCRIPTION, '') AS SEARCH_TEXT,
        ns.SERVICE_ID AS PRODUCT_ID,
        ns.SERVICE_NAME AS PRODUCT_NAME,
        ns.DESCRIPTION,
        ns.SERVICE_CATEGORY AS PRODUCT_CATEGORY,
        '非保険サービス' AS PRODUCT_TYPE,
        ns.TARGET_AUDIENCE,
        '非保険サービス' AS CONTENT_TYPE
    FROM RAW.T_SNOWLIFE_SERVICES ns
);
